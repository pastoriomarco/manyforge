#!/bin/bash
# Regenerate third_party/ros_lyrical/ros-lyrical.repos: the source set of the
# source-built ROS Lyrical base (Dockerfile.ros-lyrical-full, ROS_BASE=source).
#
# Usage (inside any container with git + python3-venv; ROS is not needed):
#   scripts/ros/generate-lyrical-source-repos.sh lyrical/2026-10-05
#
# The argument is a ros/rosdistro sync tag. The release set is the dependency
# closure of third_party/ros_lyrical/packages.txt at that sync, as upstream
# repositories at their release version tags (rosinstall_generator --upstream).
# The distribution cache is rebuilt from the tagged distribution.yaml because
# the published cache always reflects rosdistro master, not the sync.
# Version floors (third_party/ros_lyrical/floors.repos) then replace the
# matching repositories with unmodified upstream release tags, and the
# repositories listed in exclude.txt are dropped. Upstreams that
# tag releases as v<version> (eProsima, iceoryx) get that tag; every tag is
# checked to exist.
set -euo pipefail

sync_tag=${1:?usage: $0 <rosdistro sync tag, e.g. lyrical/2026-10-05>}
repo_root=$(cd "$(dirname "$0")/../.." && pwd)
manifest_dir="${repo_root}/third_party/ros_lyrical"
work=$(mktemp -d)
trap 'rm -rf "${work}"' EXIT

python3 -m venv "${work}/venv"
"${work}/venv/bin/pip" install -q rosinstall_generator==0.1.23 rosdistro==1.1.0 pyyaml
export PATH="${work}/venv/bin:${PATH}"

git clone -q --depth 1 --branch "${sync_tag}" https://github.com/ros/rosdistro "${work}/rosdistro"
rosdistro_commit=$(git -C "${work}/rosdistro" rev-parse HEAD)
(cd "${work}/rosdistro" && rosdistro_build_cache "file://${work}/rosdistro/index-v4.yaml" lyrical >/dev/null)
sed "s#distribution_cache: .*lyrical-cache.yaml.gz#distribution_cache: file://${work}/rosdistro/lyrical-cache.yaml.gz#" \
    "${work}/rosdistro/index-v4.yaml" > "${work}/rosdistro/index-local.yaml"

ROSDISTRO_INDEX_URL="file://${work}/rosdistro/index-local.yaml" \
    rosinstall_generator --rosdistro lyrical --deps --upstream --format repos \
    $(grep -v '^#' "${manifest_dir}/packages.txt") > "${work}/sync.repos"

python3 - "${work}/sync.repos" "${manifest_dir}/floors.repos" "${manifest_dir}/exclude.txt" \
    "${manifest_dir}/ros-lyrical.repos" "${sync_tag}" "${rosdistro_commit}" <<'PY'
import subprocess, sys, yaml
sync_path, floors_path, exclude_path, out_path, tag, commit = sys.argv[1:]
repos = yaml.safe_load(open(sync_path))["repositories"]
floors = yaml.safe_load(open(floors_path))["repositories"]
excluded = [l.strip() for l in open(exclude_path) if l.strip() and not l.startswith("#")]
lines = [
    "# GENERATED by scripts/ros/generate-lyrical-source-repos.sh; do not edit.",
    f"# rosdistro sync tag {tag} (ros/rosdistro {commit})",
    "# Upstream repositories at release version tags; version floors from",
    "# floors.repos override the sync (marked below); exclude.txt repositories",
    "# are dropped.",
]
for name in excluded:
    if repos.pop(name, None) is None:
        sys.exit(f"excluded {name} is not part of the sync closure")
    lines.append(f"#   excluded: {name}")
for name, entry in floors.items():
    if name not in repos:
        sys.exit(f"floor {name} is not part of the sync closure")
    lines.append(f"#   floor: {name} {repos[name]['version']} -> {entry['version']}")
    repos[name] = entry
def has_tag(url, tag):
    return subprocess.run(["git", "ls-remote", "--exit-code", url, f"refs/tags/{tag}"],
                          stdout=subprocess.DEVNULL).returncode == 0
for name, entry in repos.items():
    if has_tag(entry["url"], entry["version"]):
        continue
    if has_tag(entry["url"], "v" + entry["version"]):
        entry["version"] = "v" + entry["version"]
        continue
    sys.exit(f"no upstream release tag for {name} {entry['version']}")
out = {"repositories": {k: repos[k] for k in sorted(repos)}}
with open(out_path, "w") as f:
    f.write("\n".join(lines) + "\n")
    yaml.safe_dump(out, f, sort_keys=False, default_flow_style=False)
PY
echo "wrote ${manifest_dir}/ros-lyrical.repos (${sync_tag}, ${rosdistro_commit})"
