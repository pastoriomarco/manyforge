/// Isaac inputs.
[[nodiscard]] ControllerLaunchCommand isaac_controller_launch_command(
    const ControllerLaunchArtifacts &artifacts, const IsaacControllerLane &lane,
    const IsaacControllerLaunchInputs &inputs);

/// What one activation does with a component's launch process.
enum class ControllerLaunchDecision {
  /// No process for the component: start one.
  kStart,
  /// The running process serves exactly this configuration and the lane
  /// keeps it across Apply: keep it.
  kKeep,
  /// Stop the current process (changed, exited, or a lane that never keeps
  /// it), then start one.
  kRestart,
};

struct ControllerLaunchObservation final {
  std::string identity;
  bool keep_across_apply{false};
  bool running{false};
};

[[nodiscard]] ControllerLaunchDecision
decide_controller_launch(const std::optional<ControllerLaunchObservation> &current,
                         const ControllerLaunchCommand &next);

/// Cached readiness of the exact handle occurrence at first fault observation.
/// Unknown facts stay absent; collecting this value must not query live ROS.
struct ControllerLaunchReadinessEvidence final {
  std::optional<bool> known;
  std::optional<bool> controller_bound;
  std::optional<bool> arm_controller_active;
  std::optional<bool> controller_manager_present;
  std::optional<bool> controller_observed;
  std::optional<bool> controller_loaded;
  std::optional<bool> hardware_ready;
  std::optional<bool> joint_sample_available;
  std::optional<std::uint64_t> binding_epoch;
  std::optional<std::int64_t> sample_age_ns;
  std::string captured_utc;
};

/// Cached once at the first host observation of a launch exit. The time is
/// an observation time, not an invented controller/source timestamp.
struct ControllerLaunchExitEvidence final {
  int pid{-1};
  std::optional<int> exit_status;
  std::optional<int> signal;
  bool core_dumped{false};
  std::string observed_utc;
  std::string controllable_component_id;
  std::string launch_identity;
  std::string robot_description_sha256;
  std::string controllers_sha256;
  /// Upstream launch logging location, not a claimed captured log file.
  std::filesystem::path upstream_log_directory;
  std::string description;
  std::string request_context;
  std::optional<ControllerLaunchReadinessEvidence> readiness;
};

