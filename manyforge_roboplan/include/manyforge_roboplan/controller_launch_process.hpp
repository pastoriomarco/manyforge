/// Q78 / design §7.5 "the Manager owns the controller-manager process": the
/// command and process ownership of one component's controller launch. The
/// execution host (itself a Manager-owned child) writes the generated
/// artifacts and runs CCLC, so it starts each component's launch between the
/// two: after the artifacts are written and before CCLC activates the arm.
/// ROS-free: the launch is an external `ros2 launch` process.

class ControllerLaunchProcessError final : public std::runtime_error {
public:
  using std::runtime_error::runtime_error;
};

/// One component's controller launch command.
struct ControllerLaunchCommand final {
  std::string controllable_component_id;
  ControllerLaunchLane lane{};
  /// Full argv; argv[0] is resolved through PATH at start.
  std::vector<std::string> argv;
  /// Identity of what the process runs (lane, profile, namespace, controller
  /// names, frame prefix and the exact bytes of both generated files, never
  /// their per-activation paths). Equal identity means the running process
  /// already serves this configuration.
  std::string identity;
  /// Diagnostic identities of the exact generated bytes; no identity authority.
  std::string robot_description_sha256;
  std::string controllers_sha256;
  /// Settings of this physical launch occurrence, copied from generation.
  std::string controller_profile;
  std::string runtime_namespace;
  std::string arm_controller_name;
  std::optional<std::string> gripper_controller_name;
  std::string frame_prefix;
  std::string controllers_yaml;
  /// Mock and Isaac keep their processes across Apply when their exact
  /// launch identity is unchanged (Q21, DX224.3).
  bool keep_across_apply{false};
};

/// The mock lane command: Track 2's `mock_control.launch.py` with the
/// artifact's launch arguments (phase 2a contract, DX-175). Since CP8 step 2a
/// it is the one builder of Mock and Real ros2_control components.
[[nodiscard]] ControllerLaunchCommand
mock_controller_launch_command(const ControllerLaunchArtifacts &artifacts);

/// The Isaac lane command: `isaac_topic_based_control.launch.py` with the
/// host-owned arguments (generated files, profile, namespace, controller
/// names, frame prefix and the lane's joint topics, taken from the same lane
/// facts the generated URDF's hardware section was written from so the
/// launch's readiness topics agree with it by construction). The user opens
/// the Isaac scene; this process only attaches the ROS controller stack.
/// `gripper_state_freshness_timeout_s` is the budget of the component's
/// `gripper_feedback` stream row, passed to the launch's gripper transport
/// adapter (one source).
[[nodiscard]] ControllerLaunchCommand isaac_controller_launch_command(
    const ControllerLaunchArtifacts &artifacts, const IsaacControllerLane &lane,
    std::optional<double> gripper_state_freshness_timeout_s = std::nullopt);

/// What one activation does with a component's launch process.
enum class ControllerLaunchDecision {
  /// No process for the component: start one.
  kStart,
  /// The running process serves exactly this configuration and the lane
  /// keeps it across Apply: keep it.
  kKeep,
  /// Stop the current process (changed, exited, or a lane that never keeps
  /// it), then start one.
  kRestart,
};

struct ControllerLaunchObservation final {
  std::string identity;
  bool keep_across_apply{false};
  bool running{false};
};

[[nodiscard]] ControllerLaunchDecision
decide_controller_launch(const std::optional<ControllerLaunchObservation> &current,
                         const ControllerLaunchCommand &next);

/// Cached readiness of the exact handle occurrence at first fault observation.
