TEST(RetainedMeasuredRobotGeometry,
     UnrelatedCompiledParticipantsDoNotAlterRobotMembership) {
  GeometryFixture fixture;
  const auto original = fixture.qualify();
  ASSERT_TRUE(original.ok());
  auto unrelated = fixture.bindings.front().value();
  unrelated.controllable_component_id =
      core::ControllableComponentId("nonrobot.component");
  unrelated.retained_bundle_id = core::RetainedBundleId("unrelated.bundle");
  auto sealed = core::verify_runtime_participant_binding(std::move(unrelated));
  ASSERT_TRUE(sealed.ok()) << sealed.error().message;
  fixture.bindings.push_back(std::move(sealed.value()));
  const auto result = fixture.qualify();
  ASSERT_TRUE(result.ok()) << result.error().message;
  ASSERT_EQ(result.value().size(), 1U);
  EXPECT_EQ(result.value().front().component_id,
            original.value().front().component_id);
  EXPECT_EQ(result.value().front().required_resources,
            original.value().front().required_resources);
}

