"""Qualify the retained I3 Lite6 model through pure Composer-side FK.

The fixture is generated by the deployment compiler/materializer.  This probe
loads the exact retained URDF through the neutral structural FK consumer.  It
does not construct Composer runtime state, infer an active model, translate a
private consumer namespace, or publish a historical viewer payload.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
from typing import Any

from manyforge_composer.compiled_model_fk import (
    CompiledModelDescriptor,
    RigidTransform,
    load_compiled_model_fk,
)


def _sha256(bytes_value: bytes) -> str:
    return "sha256:" + hashlib.sha256(bytes_value).hexdigest()


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise AssertionError(message)


def _symbol(manifest: dict[str, Any], kind: str, source_name: str) -> str:
    rows = [
        row
        for row in manifest["symbol_rewrites"]
        if row["kind"] == kind
        and row["model_instance_id"] == manifest["model_instance_id"]
        and row["scope_name"] == ""
        and row["source_name"] == source_name
    ]
    if len(rows) != 1:
        raise AssertionError(
            f"expected one {kind} rewrite for {source_name}, got {rows!r}"
        )
    return str(rows[0]["compiled_name"])


def _translation(
    transforms: dict[str, RigidTransform], link_name: str
) -> tuple[float, float, float]:
    return transforms[link_name].translation


def _delta(
    before: tuple[float, float, float],
    after: tuple[float, float, float],
) -> tuple[float, float, float]:
    return tuple(after[index] - before[index] for index in range(3))


def _norm(vector: tuple[float, float, float]) -> float:
    return math.sqrt(sum(value * value for value in vector))


def qualify(fixture_root: Path) -> None:
    manifest_path = fixture_root / "manifest.json"
    urdf_path = fixture_root / "retained-model.urdf"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    urdf_bytes = urdf_path.read_bytes()
    srdf_bytes = (fixture_root / "retained-model.srdf").read_bytes()
    _require(
        manifest["api_version"] == "manyforge.i3.retained-consumer-fixture.v1",
        "retained consumer fixture API version is not qualified",
    )
    _require(
        _sha256(urdf_bytes) == manifest["urdf_sha256"],
        "retained URDF digest does not match the fixture manifest",
    )
    _require(
        _sha256(srdf_bytes) == manifest["srdf_sha256"],
        "retained SRDF digest does not match the fixture manifest",
    )
    symbol_rows = manifest["symbol_rewrites"]
    symbol_source_keys = [
        (
            row["model_instance_id"],
            row["kind"],
            row["scope_name"],
            row["source_name"],
        )
        for row in symbol_rows
    ]
    symbol_compiled_names = [row["compiled_name"] for row in symbol_rows]
    _require(
        len(symbol_source_keys) == len(set(symbol_source_keys)),
        "retained fixture contains duplicate source symbol keys",
    )
    _require(
        len(symbol_compiled_names) == len(set(symbol_compiled_names)),
        "retained fixture contains duplicate compiled symbol names",
    )

    master = _symbol(manifest, "joint", "right_finger_joint")
    follower = _symbol(manifest, "joint", "left_finger_joint")
    left_link = _symbol(manifest, "link", "lite_gripper_left_finger")
    right_link = _symbol(manifest, "link", "lite_gripper_right_finger")
    model_root = _symbol(manifest, "link", "world")
    coordinate_rows = manifest["coordinates"]
    coordinate_keys = [
        (row["model_instance_id"], row["source_joint_index"])
        for row in coordinate_rows
    ]
    _require(
        len(coordinate_keys) == len(set(coordinate_keys)),
        "retained fixture contains duplicate coordinate identities",
    )
    coordinates = {row["source_joint_name"]: row for row in coordinate_rows}
    _require(
        len(coordinates) == len(coordinate_rows),
        "retained fixture contains duplicate source joint names",
    )
    _require(
        coordinates["right_finger_joint"]["mimic_source_compiled_joint_name"]
        is None,
        "master coordinate unexpectedly has a mimic source",
    )
    _require(
        coordinates["left_finger_joint"]["mimic_source_compiled_joint_name"]
        == master,
        "follower coordinate does not reference the compiled master",
    )
    _require(
        coordinates["left_finger_joint"]["compiled_joint_name"] == follower,
        "follower coordinate has the wrong compiled joint",
    )
    _require(
        coordinates["left_finger_joint"]["mimic_multiplier"] == 1.0,
        "follower coordinate has the wrong mimic multiplier",
    )
    _require(
        coordinates["left_finger_joint"]["mimic_offset"] == 0.0,
        "follower coordinate has the wrong mimic offset",
    )
    _require(
        master < follower,
        "compiled master joint must sort before its follower",
    )

    model = load_compiled_model_fk(
        CompiledModelDescriptor(
            model_key=(
                f"{manifest['retained_bundle_id']}/{manifest['product_id']}"
            ),
            urdf_path=urdf_path,
        )
    )
    arguments = {
        "link_names": [left_link, right_link],
        "reference_frame": model_root,
    }
    closed = model.compute_link_transforms(
        joint_coordinates={master: 0.0},
        **arguments,
    )
    opened = model.compute_link_transforms(
        joint_coordinates={master: 0.004},
        **arguments,
    )
    left_delta = _delta(
        _translation(closed, left_link),
        _translation(opened, left_link),
    )
    right_delta = _delta(
        _translation(closed, right_link),
        _translation(opened, right_link),
    )
    _require(
        math.isclose(_norm(left_delta), 0.004, abs_tol=1e-10),
        "left-finger FK displacement is not exactly 4 mm",
    )
    _require(
        math.isclose(_norm(right_delta), 0.004, abs_tol=1e-10),
        "right-finger FK displacement is not exactly 4 mm",
    )
    dot = sum(
        left_delta[index] * right_delta[index] for index in range(3)
    )
    _require(
        math.isclose(dot, -(0.004**2), abs_tol=1e-12),
        "mimic fingers did not move in exactly opposite directions",
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--fixture-root", type=Path, required=True)
    arguments = parser.parse_args()
    qualify(arguments.fixture_root)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
