#pragma once

#include <cstddef>
#include <cstdint>
#include <optional>
#include <string>
#include <string_view>
#include <vector>

namespace manyforge::robot_lifecycle
{

/// Cross-vendor target intents. Adapters own every vendor/controller stage
/// needed to reach these postconditions; clients must never sequence stages.
inline constexpr std::string_view kPrepareForMotionActionId =
  "robot.prepare_for_motion";
inline constexpr std::string_view kMakeNoncommandableActionId =
  "robot.make_noncommandable";

enum class AuthorityProfile
{
  kLocalOperator,
  kExternalPlc,
};

enum class FactState
{
  kUnknown,
  kFalse,
  kTrue,
};

enum class ConfirmationClass
{
  kNone,
  kExplicit,
  kHighConsequence,
};

enum class TransactionPhase
{
  kAccepted,
  kExecuting,
  kVerifying,
  kSucceeded,
  kFailed,
  kOutcomeUnknown,
};

enum class CommandDisposition
{
  kAccepted,
  kIdempotentReplay,
  kRejected,
};

const char * authority_profile_name(AuthorityProfile profile) noexcept;
const char * fact_state_name(FactState state) noexcept;
const char * confirmation_class_name(ConfirmationClass confirmation) noexcept;
const char * transaction_phase_name(TransactionPhase phase) noexcept;
const char * command_disposition_name(CommandDisposition disposition) noexcept;

struct SupervisorConfig
{
  std::string robot_id;
  std::string supervisor_instance_id;
  AuthorityProfile authority_profile = AuthorityProfile::kLocalOperator;
  std::size_t replay_capacity = 128;
};

struct AuthoritySession
{
  AuthorityProfile profile = AuthorityProfile::kLocalOperator;
  std::string session_id;
  std::uint64_t generation = 0;
  std::string principal_id;
  std::int64_t valid_until_ns = 0;
  /// Startup epoch of the selected authority component. Session renewal never
  /// changes this value; a replacement authority creates a new session.
  std::string component_epoch;
};

struct ObservedFacets
{
  std::uint64_t generation = 0;
  /// Startup epoch generated by the independently restartable transport owner.
  std::string transport_owner_component_epoch;
  std::int64_t source_timestamp_ns = 0;
  std::int64_t received_timestamp_ns = 0;
  std::int64_t fresh_until_ns = 0;

  FactState transport_connected = FactState::kUnknown;
  FactState identity_verified = FactState::kUnknown;
  FactState position_valid = FactState::kUnknown;
  FactState robot_enabled = FactState::kUnknown;
  FactState vendor_control_ready = FactState::kUnknown;
  FactState hardware_component_active = FactState::kUnknown;
  FactState trajectory_controller_active = FactState::kUnknown;
  FactState fault_present = FactState::kUnknown;
  FactState warning_present = FactState::kUnknown;
  FactState recovery_required = FactState::kUnknown;
  FactState stationary = FactState::kUnknown;

  std::vector<std::string> adapter_blocking_reason_codes;
  /// Bounded, display-only adapter facts. Generic consumers must not derive
  /// admission or commands from these vendor-specific details.
  std::vector<std::string> adapter_status_keys;
  std::vector<std::string> adapter_status_values;
};

struct CapabilityDescriptor
{
  std::string action_id;
  std::string label;
  bool supported = false;
  bool available = false;
  std::string availability_reason;
  ConfirmationClass confirmation = ConfirmationClass::kNone;
  std::string side_effect_summary;
  std::string expected_postcondition;
  std::int64_t timeout_ns = 0;
};

struct CommandRequest
{
  std::string robot_id;
  std::string request_id;
  std::uint64_t request_sequence = 0;
  std::string action_id;
  AuthorityProfile authority_profile = AuthorityProfile::kLocalOperator;
  std::string authority_session_id;
  std::uint64_t authority_session_generation = 0;
  std::string principal_id;
  std::uint64_t expected_snapshot_generation = 0;
  std::string confirmation_evidence;
};

struct CommandDecision
{
  CommandDisposition disposition = CommandDisposition::kRejected;
  std::string reason;
  std::uint64_t transaction_generation = 0;
  TransactionPhase phase = TransactionPhase::kFailed;
  std::int64_t deadline_ns = 0;
};

struct TransactionRecord
{
  std::uint64_t generation = 0;
  std::string request_id;
  std::uint64_t request_sequence = 0;
  std::string action_id;
  std::string principal_id;
  std::uint64_t authority_session_generation = 0;
  TransactionPhase phase = TransactionPhase::kAccepted;
  std::int64_t accepted_at_ns = 0;
  std::int64_t deadline_ns = 0;
  std::int64_t terminal_at_ns = 0;
  std::string result_reason;
};

struct LifecycleSnapshot
{
  std::string robot_id;
  std::string supervisor_instance_id;
  AuthorityProfile authority_profile = AuthorityProfile::kLocalOperator;
  std::uint64_t generation = 0;
  std::uint64_t capability_generation = 0;
  std::uint64_t capability_observation_generation = 0;
  std::optional<AuthoritySession> authority_session;
  ObservedFacets observed;
  std::vector<CapabilityDescriptor> capabilities;
  std::optional<TransactionRecord> pending_transaction;
  std::optional<TransactionRecord> last_terminal_transaction;

  std::uint64_t transport_owner_progress_sequence = 0;
  std::int64_t transport_owner_progress_received_timestamp_ns = 0;
  bool transport_owner_progress_healthy = false;
  std::string transport_owner_progress_reason;
  bool observation_fresh = false;
  bool authority_fresh = false;
  bool observe_ready = false;
  bool controller_ready = false;
  bool motion_admitted = false;
  bool recovery_required = false;
  bool reconciliation_required = false;
  std::vector<std::string> admission_reason_codes;
};

}  // namespace manyforge::robot_lifecycle
